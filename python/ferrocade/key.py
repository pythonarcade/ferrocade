# Modifier flags (either side counts; SYSTEM is the Windows / Command key).
MOD_SHIFT = 1
MOD_CTRL = 2
MOD_ALT = 4
MOD_SYSTEM = 8


_NAMES = {value: name for name, value in globals().copy().items()
          if name.isupper() and not name.startswith("MOD_")}


def name(key: int) -> str:
    """The constant's name for a key code, for example `name(LEFT) == "LEFT"`."""
    try:
        return _NAMES[key]
    except (KeyError, TypeError):
        raise ValueError(f"unknown key code {key!r}") from None
