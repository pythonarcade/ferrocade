"""Generate python/ferrocade/key.py from the engine's key table (crates/ferrocade/src/input.rs).

The generated module is plain Python (no extension import), so the browser build loads the same
file. Run from the repository root after `maturin develop`:

    python tools/gen_keys.py          # write python/ferrocade/key.py
    python tools/gen_keys.py --check  # exit 1 if the file is out of date
"""

import sys
from pathlib import Path

from ferrocade._ferrocade import _key_table

OUT = Path(__file__).resolve().parent.parent / "python" / "ferrocade" / "key.py"

HEADER = '''"""Keyboard constants for `on_key_press`, `on_key_release`, and `Window.is_key_pressed`.

Keys are physical positions, named after a US QWERTY keyboard: on an AZERTY keyboard, the key
labeled Z reports `W`, so WASD controls work on any layout. `modifiers` in the key callbacks is a
combination of the `MOD_*` flags, for example `modifiers & key.MOD_SHIFT`.

Generated by tools/gen_keys.py from the engine's key table. Do not edit by hand.
"""

'''

FOOTER = '''

_NAMES = {value: name for name, value in globals().copy().items()
          if name.isupper() and not name.startswith("MOD_")}


def name(key: int) -> str:
    """The constant's name for a key code, for example `name(LEFT) == "LEFT"`."""
    try:
        return _NAMES[key]
    except (KeyError, TypeError):
        raise ValueError(f"unknown key code {key!r}") from None
'''


def render():
    table = _key_table()
    keys = [(n, v) for n, v in table if not n.startswith("MOD_")]
    mods = [(n, v) for n, v in table if n.startswith("MOD_")]
    lines = [f"{n} = {v}" for n, v in keys]
    lines += ["", "# Modifier flags (either side counts; SYSTEM is the Windows / Command key)."]
    lines += [f"{n} = {v}" for n, v in mods]
    return HEADER + "\n".join(lines) + "\n" + FOOTER


def main():
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is out of date; run python tools/gen_keys.py")
            return 1
        print(f"{OUT} is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
